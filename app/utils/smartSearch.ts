function buildSynonymsMap(clusters: string[][]): Record<string, string[]> {
  const map: Record<string, string[]> = {};
  for (const cluster of clusters) {
    const canonical = normalizeText(cluster[0] || "");
    for (const rawToken of cluster) {
      const token = normalizeText(rawToken);
      if (!token) continue;
      if (!map[token]) {
        map[token] = [];
      }
      if (canonical && canonical !== token && !map[token]!.includes(canonical)) {
        map[token]!.unshift(canonical);
      }
      for (const rawOther of cluster) {
        const other = normalizeText(rawOther);
        if (other && other !== token && !map[token]!.includes(other)) {
          map[token]!.push(other);
        }
      }
    }
  }
  return map;
}

