/**
 * Нормалізація тексту (приведення до нижнього регістру, заміна суміжних літер)
 */
export function normalizeText(text: string): string {
  if (!text) return "";
  return text
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/ы/g, "и")
    .replace(/э/g, "е")
    .replace(/ъ/g, "'")
    .replace(/[^\p{L}\p{N}\s]/gu, " ")
    .trim();
}

