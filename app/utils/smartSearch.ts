/**
 * Фонетичне зіставлення символів (укр і/ї/и, е/є вважаються рівнозначними при пошуку)
 */
function areCharactersPhoneticallyEqual(a: string, b: string): boolean {
  if (a === b) return true;
  // Українська 'і', 'и', 'ї' та російська 'и'
  const isIEquivalent = (ch: string) => ch === "і" || ch === "и" || ch === "ї" || ch === "i";
  if (isIEquivalent(a) && isIEquivalent(b)) return true;
  
  // 'е' та 'є'
  const isEEquivalent = (ch: string) => ch === "е" || ch === "є";
  if (isEEquivalent(a) && isEEquivalent(b)) return true;

  // 'г' та 'ґ'
  const isGEquivalent = (ch: string) => ch === "г" || ch === "ґ";
  if (isGEquivalent(a) && isGEquivalent(b)) return true;

  return false;
}

/**
 * Перевірка, чи є prefix фонетичним початком word
 */
function isPhoneticPrefix(prefix: string, word: string): boolean {
  if (word.length < prefix.length) return false;
  for (let i = 0; i < prefix.length; i++) {
    if (!areCharactersPhoneticallyEqual(prefix[i]!, word[i]!)) {
      return false;
    }
  }
  return true;
}

/**
 * Відстань Дамерау-Левенштейна з урахуванням фонетики та перестановки сусідніх символів
 * Дозволяє знаходити слова з одруківками (наприклад, "гіпокартон" -> "гіпсокартон", "гипскоартон" -> "гіпсокартон")
 */
export function damerauLevenshtein(source: string, target: string): number {
  const sLen = source.length;
  const tLen = target.length;
  if (sLen === 0) return tLen;
  if (tLen === 0) return sLen;

  const d: number[][] = [];
  for (let i = 0; i <= sLen; i++) {
    d[i] = [];
    d[i]![0] = i;
  }
  for (let j = 0; j <= tLen; j++) {
    d[0]![j] = j;
  }

  for (let i = 1; i <= sLen; i++) {
    const sChar = source[i - 1]!;
    for (let j = 1; j <= tLen; j++) {
      const tChar = target[j - 1]!;
      const cost = areCharactersPhoneticallyEqual(sChar, tChar) ? 0 : 1;

      d[i]![j] = Math.min(
        d[i - 1]![j]! + 1,       // видалення
        d[i]![j - 1]! + 1,       // вставка
        d[i - 1]![j - 1]! + cost // заміна
      );

      // Транспозиція (перестановка сусідніх літер, наприклад "ск" <-> "кс")
      if (
        i > 1 &&
        j > 1 &&
        areCharactersPhoneticallyEqual(sChar, target[j - 2]!) &&
        areCharactersPhoneticallyEqual(source[i - 2]!, tChar)
      ) {
        d[i]![j] = Math.min(d[i]![j]!, d[i - 2]![j - 2]! + 1);
      }
    }
  }

  return d[sLen]![tLen]!;
}

/**
 * Виділяє основу слова, відкидаючи типові закінчення відмінків та прикметників
 */
function getWordStem(word: string): string {
  if (word.length <= 3) return word;
  return word.replace(
    /(?:очка|ечка|очки|ечки|очек|ечек|овий|евий|ний|ній|ный|ная|ное|ні|ські|ский|ская|ское|ості|ости|ость|ів|ов|ев|ей|ями|ами|ях|ах|ом|ем|им|ым|их|ых|ого|его|ому|ему|ою|ею|ам|ям|ий|ый|ій|ой|а|я|у|ю|е|і|и|о)$/u,
    ""
  );
}

/**
 * Перевірка схожості окремого слова з пошуковим токеном
 */
function isWordFuzzyMatch(queryToken: string, targetWord: string): boolean {
  // 1. Фонетичний префіксний збіг (наприклад, "гип" знаходить "гіпсокартон", "гкл" знаходить "гклв")
  if (isPhoneticPrefix(queryToken, targetWord)) return true;

  // 2. Зіставлення основ слів (стемінг для відмінків та закінчень: "відкосів" <-> "откос", "блоків" <-> "блок")
  const qStem = getWordStem(queryToken);
  const tStem = getWordStem(targetWord);
  if (qStem.length >= 3 && tStem.length >= 3) {
    if (isPhoneticPrefix(qStem, tStem) || isPhoneticPrefix(tStem, qStem)) {
      return true;
    }
  }

  // 3. Для дуже коротких токенів (до 2 символів) тільки префіксний збіг
  if (queryToken.length <= 2) {
    return false;
  }

  // 4. Для токенів довжиною 3 символи (наприклад "гкл", "лак", "осб") перевіряємо точний збіг або префікс
  if (queryToken.length === 3) {
    return targetWord === queryToken || targetWord.startsWith(queryToken);
  }

  // 5. Для слів довжиною 4+ символів застосовуємо Damerau-Levenshtein
  // 4-5 символів: дозволена 1 одруківка; 6+ символів: дозволено до 2 одруківок
  const maxDistance = queryToken.length >= 6 ? 2 : 1;
  
  // Якщо цільове слово довше за токен, перевіряємо префікс довжини токена
  if (targetWord.length >= queryToken.length) {
    const targetPrefix = targetWord.slice(0, queryToken.length);
    const prefixDist = damerauLevenshtein(queryToken, targetPrefix);
    if (prefixDist <= maxDistance) return true;
  }

  // Повна відстань має сенс тільки тоді, коли різниця в довжині не перевищує maxDistance
  if (Math.abs(queryToken.length - targetWord.length) <= maxDistance) {
    const fullDist = damerauLevenshtein(queryToken, targetWord);
    return fullDist <= maxDistance;
  }

  return false;
}

const variantsCache = new Map<string, string[]>();

/**
 * Отримує всі пошукові варіанти для токена (включно із синонімами та основами слів)
 */
function expandQueryTokenWithSynonyms(token: string): string[] {
  const cached = variantsCache.get(token);
  if (cached) return cached;

  const variants = new Set<string>([token]);
  const stem = getWordStem(token);
  if (stem && stem !== token) {
    variants.add(stem);
  }

  const syns = CONSTRUCTION_SYNONYMS[token];
  if (syns) {
    syns.forEach((s) => variants.add(s));
  }
  if (stem && stem !== token) {
    const stemSyns = CONSTRUCTION_SYNONYMS[stem];
    if (stemSyns) {
      stemSyns.forEach((s) => variants.add(s));
    }
  }

  const result = Array.from(variants);
  variantsCache.set(token, result);
  return result;
}

/**
 * Розбиває цільовий текст на слова, включаючи комбінації суміжних токенів (наприклад, "см" + "11" -> "см11")
 */
function extractTargetWords(normalizedTarget: string): string[] {
  const rawWords = normalizedTarget.split(/\s+/).filter(Boolean);
  const words = [...rawWords];
  for (let i = 0; i < rawWords.length - 1; i++) {
    words.push(rawWords[i]! + rawWords[i + 1]!);
  }
  return words;
}

/**
 * Кеш результатів текстового пошуку для запобігання повторних важких обчислень
 */
const MATCH_CACHE_LIMIT = 5000;
const matchResultCache = new Map<string, boolean>();

function getMatchCacheKey(text: string, query: string): string {
  return `${query}___${text}`;
}

/**
 * Розумна перевірка збігу тексту з пошуковим запитом (з кешуванням та fast-path)
 */
export function matchesQueryText(text: string, query: string): boolean {
  if (!query.trim()) return true;
  if (!text) return false;

  const cacheKey = getMatchCacheKey(text, query);
  const cached = matchResultCache.get(cacheKey);
  if (cached !== undefined) {
    return cached;
  }

  const normalizedQuery = normalizeText(query);
  const normalizedTarget = normalizeText(text);

  // 1. Швидка перевірка: пряме входження цілої фрази
  if (normalizedTarget.includes(normalizedQuery)) {
    if (matchResultCache.size >= MATCH_CACHE_LIMIT) matchResultCache.clear();
    matchResultCache.set(cacheKey, true);
    return true;
  }

  // 2. Перевірка синоніма всієї фрази (наприклад, "маячна рейка" -> "маяк")
  const phraseSynonyms = CONSTRUCTION_SYNONYMS[normalizedQuery];
  if (phraseSynonyms && phraseSynonyms.some((s) => normalizedTarget.includes(s))) {
    if (matchResultCache.size >= MATCH_CACHE_LIMIT) matchResultCache.clear();
    matchResultCache.set(cacheKey, true);
    return true;
  }

  let queryTokens = normalizedQuery.split(/\s+/).filter(Boolean);
  if (queryTokens.length > 1) {
    // Відфільтровуємо незначущі службові слова (прийменники)
    queryTokens = queryTokens.filter((t) => !STOP_WORDS.has(t));
  }

  if (queryTokens.length === 0) {
    if (matchResultCache.size >= MATCH_CACHE_LIMIT) matchResultCache.clear();
    matchResultCache.set(cacheKey, true);
    return true;
  }

  const targetWords = extractTargetWords(normalizedTarget);

  // Кожен токен із запиту повинен знайти хоча б один збіг у тексті цілі
  const isMatch = queryTokens.every((token) => {
    const variants = expandQueryTokenWithSynonyms(token);

    return variants.some((variant) => {
      // 1. Пряме входження варіанту в текст (для слів від 4 символів)
      if (variant.length >= 4 && normalizedTarget.includes(variant)) return true;

      // 2. Зіставлення зі словами тексту (точний початок, фонетика, одруківки, комбінації кодів)
      return targetWords.some((word) => isWordFuzzyMatch(variant, word));
    });
  });

  if (matchResultCache.size >= MATCH_CACHE_LIMIT) matchResultCache.clear();
  matchResultCache.set(cacheKey, isMatch);
  return isMatch;
}

/**
 * Перевірка товару на збіг із пошуковим запитом
 */
export function matchesSmartSearch(
  product: { title?: string; description?: string },
  query: string,
  searchInDescription = false
): boolean {
  if (!query.trim()) return true;

  // 1. Пошук у заголовку
  if (product.title && matchesQueryText(product.title, query)) {
    return true;
  }

  // 2. Пошук в описі (якщо увімкнена галочка)
  if (searchInDescription && product.description) {
    if (matchesQueryText(product.description, query)) {
      return true;
    }
  }

  return false;
}

export interface CategoryMatchSubcategory {
  id: string;
  name: string;
  count: number;
}

export interface CategoryMatchGroup {
  id: string;
  name: string;
  icon: string;
  count: number;
  subcategories: CategoryMatchSubcategory[];
}

export interface SearchMatchBreakdown {
  totalMatches: number;
  categories: CategoryMatchGroup[];
}

/**
 * Групує знайдені товари за категоріями та підкатегоріями
 */
export function getCategoryMatchBreakdown(
  products: any[],
  categoryData: CategoryItem[]
): SearchMatchBreakdown {
  const categoryCounts = new Map<string, number>(); // category_id -> count

  for (const product of products) {
    const catId = product.category_id || product.category;
    if (!catId) continue;
    categoryCounts.set(catId, (categoryCounts.get(catId) || 0) + 1);
  }

  const groups: CategoryMatchGroup[] = [];

  for (const mainCat of categoryData) {
    let mainCatTotal = categoryCounts.get(mainCat.id) || 0;
    const matchingSubs: CategoryMatchSubcategory[] = [];

    for (const sub of mainCat.subcategories) {
      const subCount = categoryCounts.get(sub.id) || 0;
      if (subCount > 0) {
        mainCatTotal += subCount;
        matchingSubs.push({
          id: sub.id,
          name: sub.name,
          count: subCount,
        });
      }
    }

    if (mainCatTotal > 0) {
      groups.push({
        id: mainCat.id,
        name: mainCat.name,
        icon: mainCat.icon,
        count: mainCatTotal,
        subcategories: matchingSubs,
      });
    }
  }

  // Сортуємо групи за кількістю знайдених позицій (найбільші спочатку)
  groups.sort((a, b) => b.count - a.count);

  return {
    totalMatches: products.length,
    categories: groups,
  };
}

/**
 * Перетворює пошуковий запит користувача на його український відповідник для SQL-пошуку.
 * Якщо користувач ввів російською (наприклад, "гипсокартон", "кирпич", "краска", "пенопласт"),
 * функція повертає "гіпсокартон", "цегла", "фарба", "пінопласт".
 */
export function getUkrainianSearchQuery(query: string): string {
  if (!query) return "";
  const tokens = query.trim().split(/\s+/);
  const mapped = tokens.map((token) => {
    const norm = normalizeText(token);
    if (!norm) return token;

    // Якщо слово вже містить специфічні українські літери
    if (/[іїєґ]/i.test(norm)) {
      return norm;
    }

    const syns = CONSTRUCTION_SYNONYMS[norm] || [];
    // 1. Беремо канонічний відповідник із синонімічного кластера
    if (syns.length > 0) return syns[0]!;

    // 2. Автоматична евристична нормалізація російських літер
    return norm
      .replace(/ы/g, "и")
      .replace(/э/g, "е")
      .replace(/ъ/g, "'");
  });
  return mapped.join(" ");
}

/**
 * Повертає пошукові варіанти для запиту (оригінал + переклад/синоніми UK <-> RU).
 * Забезпечує знаходження оголошень, створених як українською, так і російською мовами.
 * Наприклад:
 * - "гипсокартон" -> ["гипсокартон", "гіпсокартон"]
 * - "гіпсокартон" -> ["гіпсокартон", "гипсокартон"]
 * - "краска" -> ["краска", "фарба"]
 * - "фарба" -> ["фарба", "краска"]
 */
export function getSearchQueryVariants(query: string): string[] {
  if (!query) return [];
  const raw = query.trim();
  if (raw.length < 3) return [raw];

  const variants = new Set<string>();
  variants.add(raw);

  // 1. Отримуємо український відповідник
  const ukr = getUkrainianSearchQuery(raw);
  if (ukr && ukr.toLowerCase() !== raw.toLowerCase()) {
    variants.add(ukr);
  }

  // 2. Отримуємо відповідники зі словника будівельних матеріалів (RU <-> UK)
  const norm = normalizeText(raw);
  const syns = CONSTRUCTION_SYNONYMS[norm] || [];
  for (const s of syns) {
    if (s && s.length >= 3 && variants.size < 3) {
      variants.add(s);
    }
  }

  return Array.from(variants);
}

